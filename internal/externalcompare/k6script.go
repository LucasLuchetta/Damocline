package externalcompare

import (
	"encoding/json"
	"fmt"
	"regexp"
	"sort"
	"strings"
	"time"

	"github.com/LucasLuchetta/Damocline/internal/config"
)

var envRef = regexp.MustCompile(`\$\{([A-Za-z_][A-Za-z0-9_]*)\}`)

// K6Script renders an equivalent closed-loop k6 script for a single-workflow
// Damocline scenario: same paths and methods, same VUs and duration, same
// fixed think time between steps (none after the last step, as in Damocline),
// constant VUs (ramp_up is not reproduced), and the same success rule (expected_status,
// or 2xx by default, plus must_contain). The base URL and every header value
// come from environment variables so no credential is written to the script.
// Scenarios with arrival mode, weighted profiles, extraction, request bodies,
// JSON assertions, CSV data or variable think time are rejected rather than
// approximated.
func K6Script(s config.Scenario) (string, error) {
	if s.Mode != "" && s.Mode != "closed" {
		return "", fmt.Errorf("only closed-loop scenarios are supported (mode %q)", s.Mode)
	}
	if len(s.Profiles) > 0 || len(s.Workflows) > 0 {
		return "", fmt.Errorf("weighted profiles/workflows are not supported; export one workflow as a single-step-list scenario")
	}
	if s.ThinkTimeRange != nil || len(s.ThinkTimeSamples) > 0 || s.Data != nil {
		return "", fmt.Errorf("variable think time and CSV data are not supported")
	}
	if len(s.Steps) == 0 || s.Users <= 0 {
		return "", fmt.Errorf("scenario needs users and steps")
	}
	dur, err := time.ParseDuration(s.Duration)
	if err != nil {
		return "", fmt.Errorf("duration: %w", err)
	}
	think := time.Duration(0)
	if s.ThinkTime != "" {
		if think, err = time.ParseDuration(s.ThinkTime); err != nil {
			return "", fmt.Errorf("think_time: %w", err)
		}
	}
	timeout := "30s"
	if s.Timeout != "" {
		timeout = s.Timeout
	}
	q := func(v any) string { b, _ := json.Marshal(v); return string(b) }
	var b strings.Builder
	b.WriteString("// Generated by lab/k6-compare/scenario-to-k6 from a Damocline scenario.\n")
	b.WriteString("// Closed loop: each VU runs the steps in order with the scenario think time\n// between steps. Header values and the base URL come from the environment.\n")
	b.WriteString("import http from 'k6/http';\nimport { check, sleep } from 'k6';\n\n")
	b.WriteString("const BASE = __ENV.BASE_URL;\nif (!BASE) { throw new Error('set BASE_URL'); }\n\n")
	fmt.Fprintf(&b, "export const options = {\n  scenarios: { closed: { executor: 'constant-vus', vus: %d, duration: %s } },\n  summaryTrendStats: ['avg', 'min', 'med', 'max', 'p(90)', 'p(95)', 'p(99)'],\n};\n\n", s.Users, q(dur.String()))
	b.WriteString("function env(name) {\n  const v = __ENV[name];\n  if (v === undefined) { throw new Error('missing env ' + name); }\n  return v;\n}\n\n")
	b.WriteString("export default function () {\n")
	for i, st := range s.Steps {
		if st.BodyEnv != "" || len(st.Extract) > 0 || len(st.JSONAssertions) > 0 {
			return "", fmt.Errorf("step %q uses body_env, extract or json_assertions, which the kit does not translate", st.Name)
		}
		if strings.Contains(st.Path, "${") {
			return "", fmt.Errorf("step %q path uses placeholders, which the kit does not translate", st.Name)
		}
		method := strings.ToUpper(st.Method)
		if method == "" {
			method = "GET"
		}
		names := make([]string, 0, len(st.Headers))
		for k := range st.Headers {
			names = append(names, k)
		}
		sort.Strings(names)
		fmt.Fprintf(&b, "  {\n    const headers = {")
		for j, k := range names {
			if j > 0 {
				b.WriteString(",")
			}
			fmt.Fprintf(&b, " %s: %s", q(k), headerExpr(st.Headers[k], i, k))
		}
		fmt.Fprintf(&b, " };\n    const res = http.request(%s, BASE + %s, null, { headers, timeout: %s, tags: { name: %s }, redirects: 0 });\n", q(method), q(st.Path), q(timeout), q(st.Name))
		statusRule := "res.status >= 200 && res.status <= 299"
		if len(st.ExpectedStatus) > 0 {
			statusRule = q(st.ExpectedStatus) + ".includes(res.status)"
		}
		fmt.Fprintf(&b, "    check(res, { %s: (r) => { const res = r; return %s", q(st.Name+" success"), statusRule)
		if st.MustContain != "" {
			fmt.Fprintf(&b, " && typeof res.body === 'string' && res.body.includes(%s)", q(st.MustContain))
		}
		b.WriteString("; } });\n  }\n")
		if think > 0 && i < len(s.Steps)-1 {
			fmt.Fprintf(&b, "  sleep(%g);\n", think.Seconds())
		}
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// headerExpr turns `${NAME}` references into env lookups and other literal
// values into a per-header env variable K6_H_<step>_<header> so the script
// never embeds a header value.
func headerExpr(value string, step int, name string) string {
	if m := envRef.FindStringSubmatch(value); m != nil && m[0] == value {
		return fmt.Sprintf("env(%q)", m[1])
	}
	key := strings.ToUpper(regexp.MustCompile(`[^A-Za-z0-9]`).ReplaceAllString(name, "_"))
	return fmt.Sprintf("env(%q)", fmt.Sprintf("K6_H_%d_%s", step, key))
}
